#!/usr/bin/env python3
"""Render deploy/base/prometheus-rules.yaml from deploy/monitoring/prometheus/alerts.yml.

    python3 scripts/sync_alert_rules.py           # write
    python3 scripts/sync_alert_rules.py --check   # CI: exit 1 if out of sync
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "deploy/monitoring/prometheus/alerts.yml"
DST = ROOT / "deploy/base/prometheus-rules.yaml"


def render() -> str:
    groups = yaml.safe_load(SRC.read_text())["groups"]
    doc = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "agency-alerts", "labels": {"release": "prometheus"}},
        "spec": {"groups": groups},
    }
    return "# GENERATED by scripts/sync_alert_rules.py from deploy/monitoring/prometheus/alerts.yml -- do not edit.\n" + \
        yaml.safe_dump(doc, sort_keys=False, width=120)


if __name__ == "__main__":
    out = render()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != out:
            sys.exit("prometheus-rules.yaml is out of sync: run python3 scripts/sync_alert_rules.py")
        print("alert rules in sync")
    else:
        DST.write_text(out)
        print(f"wrote {DST.relative_to(ROOT)}")
