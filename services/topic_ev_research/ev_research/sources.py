"""Grounded fact retrieval: search -> SSRF check -> crawl -> schema extraction
(via the model gateway, low tier) -> deterministic on-page verification -> cache.

Facts never come from the model's memory. Image URLs come structurally from
the crawl (never generated by the model).
"""
import asyncio
import json
import logging
from collections.abc import Callable
from datetime import UTC, datetime
from decimal import Decimal
from typing import Any
from urllib.parse import urljoin

import pycountry
from crawl4ai import AsyncWebCrawler, BrowserConfig, CrawlerRunConfig, LLMConfig, LLMExtractionStrategy
from pydantic import BaseModel, Field

from agency_platform.agents.base import RunContext
from agency_platform.errors import UpstreamError
from agency_platform.security.content import UNTRUSTED_DATA_RULES
from agency_platform.security.grounding import number_appears
from agency_platform.security.ssrf import UnsafeURLError, assert_public_url
from agency_platform.tools.search import WebSearch
from ev_research import repository as repo
from ev_research.params import params, settings

logger = logging.getLogger(__name__)


class EVSpecExtraction(BaseModel):
    battery_kwh: float | None = Field(None, description="Usable battery capacity in kWh")
    range_km: float | None = Field(None, description="Rated range in km (WLTP or EPA)")
    max_charging_kw: float | None = Field(None, description="Max DC fast-charging power in kW")
    efficiency_wh_km: float | None = Field(None, description="Energy consumption in Wh/km")
    base_price: float | None = Field(None, description="Base/starting price, number only")
    price_currency: str | None = Field(None, description="ISO currency code of base_price")


class PriceExtraction(BaseModel):
    price: float | None = Field(None, description="Current price per unit, number only")
    currency: str | None = Field(None, description="ISO currency code")


SPEC_NUMERIC = ("battery_kwh", "range_km", "max_charging_kw", "efficiency_wh_km", "base_price")


class CrawlerPool:
    """One long-lived headless browser per pod, bounded concurrency."""

    def __init__(self) -> None:
        self._crawler: AsyncWebCrawler | None = None
        self._sem: asyncio.Semaphore | None = None

    async def start(self) -> None:
        self._crawler = AsyncWebCrawler(config=BrowserConfig(headless=True, verbose=False))
        await self._crawler.start()
        self._sem = asyncio.Semaphore(params().crawl.max_concurrent_crawls)

    async def stop(self) -> None:
        if self._crawler is not None:
            await self._crawler.close()

    async def extract(self, url: str, schema: type[BaseModel], instruction: str, ctx: RunContext) -> dict[str, Any] | None:
        assert self._crawler is not None and self._sem is not None, "crawler not started"
        await assert_public_url(url)
        cfg = params().crawl
        llm = ctx.llm.openai_compat(task="extraction")
        strategy = LLMExtractionStrategy(
            llm_config=LLMConfig(provider=f"openai/{llm.model}", api_token=llm.api_key, base_url=llm.base_url,
                                 temperature=0.0),
            schema=schema.model_json_schema(),
            extraction_type="schema",
            instruction=f"{instruction}\n\n{UNTRUSTED_DATA_RULES}",
            chunk_token_threshold=cfg.chunk_token_threshold,
            force_json_response=True,  # plain JSON-mode instead of crawl4ai's <blocks> convention
        )
        run_cfg = CrawlerRunConfig(extraction_strategy=strategy, page_timeout=cfg.page_timeout_s * 1000)
        async with self._sem:
            result = await self._crawler.arun(url=url, config=run_cfg)
        if not result.success or not result.extracted_content:
            return None
        data = _merge_chunks(result.extracted_content)
        page_text = str(getattr(result, "markdown", "") or "")
        if cfg.verify_numbers_on_page:
            data = _verify_on_page(data, page_text, url)
        data["_source_url"] = url
        data["_image_url"] = _pick_image(result, url)
        return data


def _merge_chunks(raw: str) -> dict[str, Any]:
    """crawl4ai returns one object or a list (one per chunk): keep first non-null per field."""
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        return {}
    merged: dict[str, Any] = {}
    for chunk in parsed if isinstance(parsed, list) else [parsed]:
        if isinstance(chunk, dict):
            for k, v in chunk.items():
                if v is not None and merged.get(k) is None and not k.startswith("_") and k != "error":
                    merged[k] = v
    return merged


def _verify_on_page(data: dict[str, Any], page_text: str, url: str) -> dict[str, Any]:
    """Null any number the model reported that isn't literally on the page."""
    for key, value in list(data.items()):
        if isinstance(value, int | float) and not isinstance(value, bool):
            if not number_appears(value, page_text):
                logger.warning("extracted number not found on page; dropped", extra={"field": key, "url": url})
                data[key] = None
    return data


def country_name(code: str) -> str:
    """'DE' -> 'Germany'. Search engines read bare codes as other things (DE = Delaware)."""
    country = pycountry.countries.get(alpha_2=code.upper())
    return getattr(country, "common_name", None) or (country.name if country else code)


def _pick_image(result: Any, page_url: str) -> str | None:
    images = (getattr(result, "media", None) or {}).get("images", [])
    if not images:
        return None
    src = max(images, key=lambda img: img.get("score") or 0).get("src")
    return urljoin(page_url, src) if src else None


class FactSources:
    def __init__(self, crawler: CrawlerPool, search: WebSearch) -> None:
        self._crawler = crawler
        self._search = search

    async def _candidate_urls(self, query: str) -> list[str]:
        results = await self._search.search(query, max_results=params().crawl.candidate_sources)
        return [r.url for r in results]

    async def _first_usable(
        self, urls: list[str], schema: type[BaseModel], instruction: str,
        usable: Callable[[dict[str, Any]], bool], ctx: RunContext,
    ) -> dict[str, Any]:
        last = "no search results"
        for url in urls:
            try:
                data = await self._crawler.extract(url, schema, instruction, ctx)
            except UnsafeURLError as exc:
                last = f"blocked unsafe URL ({exc})"
                continue
            except Exception as exc:  # one bad page must not sink the run
                logger.warning("crawl failed", extra={"url": url, "error": type(exc).__name__})
                last = f"crawl failed for {url}"
                continue
            if data and usable(data):
                return data
            last = f"no verifiable data on {url}"
        raise UpstreamError(f"Could not find verifiable data ({last}; tried {len(urls)} sources)")

    async def ev_specs(self, make: str, model: str, year: int, trim: str, ctx: RunContext) -> dict[str, Any]:
        if cached := await repo.get_cached_specs(make, model, year, trim):
            return {**cached, "from_cache": True}
        query = f"{year} {make} {model} {trim} specifications battery kWh range charging".strip()
        data = await self._first_usable(
            await self._candidate_urls(query),
            EVSpecExtraction,
            (
                f"Extract the official specifications for the {year} {make} {model} {trim}: battery capacity "
                "(kWh), range (km), max DC fast-charging power (kW), energy consumption (Wh/km), base price "
                "and currency. Only use numbers explicitly stated on this page. Leave a field null if absent."
            ),
            lambda d: any(d.get(f) is not None for f in SPEC_NUMERIC[:4]),
            ctx,
        )
        record = {
            **{k: data.get(k) for k in SPEC_NUMERIC},
            "price_currency": data.get("price_currency"),
            "image_url": data.get("_image_url"),
            "source_url": data.get("_source_url"),
        }
        await repo.store_specs(make, model, year, trim, record)
        return {**(await repo.get_cached_specs(make, model, year, trim) or record), "from_cache": False}

    async def country_price(self, country_code: str, metric: str, ctx: RunContext) -> dict[str, Any]:
        if cached := await repo.get_cached_price(country_code, metric):
            return {**cached, "value": float(cached["value"]), "from_cache": True}
        label = metric.replace("_", " ")
        name = country_name(country_code)
        data = await self._first_usable(
            await self._candidate_urls(f"average household {label} in {name} {datetime.now(UTC).year}"),
            PriceExtraction,
            f"Extract the current national average {label} in {name} (country code {country_code}) stated on this "
            f"page, as a number and its ISO currency. Ignore values for other countries or for regions/states. "
            "Only use the value explicitly stated on this page.",
            lambda d: d.get("price") is not None and d.get("price") > 0,
            ctx,
        )
        value = float(Decimal(str(data["price"])))
        await repo.store_price(country_code, metric, value, data.get("currency") or "USD", data.get("_source_url"))
        return {"value": value, "currency": data.get("currency") or "USD", "source_url": data.get("_source_url"),
                "from_cache": False}


def build_search(http) -> WebSearch:
    key = settings().tavily_api_key
    return WebSearch(key.get_secret_value() if key else None, http)
